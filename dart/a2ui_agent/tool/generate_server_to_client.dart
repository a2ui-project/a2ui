/// Copies the specification's `server_to_client.json` (v0.9) and
/// `agent_to_renderer.json` (v1.0) into Dart source, so the published package
/// can show a model the message schema without reading the specification
/// repository.
///
/// Run from the package directory after editing the specification:
///
/// ```sh
/// dart run tool/generate_server_to_client.dart
/// ```
///
/// `test/direct_json_test.dart` fails if the checked-in output has drifted
/// from the specification.
library;

import 'dart:io';

/// The v0.9 specification file to copy, relative to the repository root.
const String sourceV0_9 = 'specification/v0_9/json/server_to_client.json';

/// The v1.0 specification file to copy, relative to the repository root.
const String sourceV1_0 = 'specification/v1_0/json/agent_to_renderer.json';

/// The file to write, relative to the package directory.
const String output =
    'lib/src/inference_formats/direct_json/server_to_client.g.dart';

void main() {
  final String jsonV0_9 = readSource(sourceV0_9);
  final String jsonV1_0 = readSource(sourceV1_0);
  File(output).writeAsStringSync(render(jsonV0_9, jsonV1_0));
  stdout.writeln('Wrote $output from $sourceV0_9 and $sourceV1_0.');
}

/// Reads [source], searching upwards for the repository root so the tool runs
/// from the package directory or the workspace root.
String readSource(String source) {
  Directory dir = Directory.current;
  while (true) {
    final candidate = File('${dir.path}/$source');
    if (candidate.existsSync()) return candidate.readAsStringSync();
    final Directory parent = dir.parent;
    if (parent.path == dir.path) {
      throw StateError(
        'Could not find $source above ${Directory.current.path}.',
      );
    }
    dir = parent;
  }
}

void _checkEmbeddable(String source, String json) {
  if (json.contains("'''")) {
    throw StateError("$source contains ''', which ends the string literal.");
  }
  if (json.endsWith("'")) {
    throw StateError("$source ends with ', which extends the delimiter.");
  }
  if (!json.startsWith('{')) {
    throw StateError('$source does not start with a JSON object.');
  }
}

/// Wraps [jsonV0_9] and [jsonV1_0] in a Dart library, verbatim, so the
/// generated file diffs against the specification one line at a time.
String render(String jsonV0_9, String jsonV1_0) {
  _checkEmbeddable(sourceV0_9, jsonV0_9);
  _checkEmbeddable(sourceV1_0, jsonV1_0);
  return '''
// Copyright 2024 Google LLC
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     https://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// Generated by tool/generate_server_to_client.dart. Do not edit by hand.
//
// Verbatim copies of $sourceV0_9 and $sourceV1_0.

/// The `server_to_client.json` document for protocol v0.9, as published.
const String serverToClientV0_9Json = r\'\'\'
$jsonV0_9\'\'\';

/// The `agent_to_renderer.json` document for protocol v1.0, as published.
const String agentToRendererV1_0Json = r\'\'\'
$jsonV1_0\'\'\';
''';
}
