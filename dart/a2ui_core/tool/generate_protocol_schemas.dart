/// Copies the specification's protocol schemas, `common_types.json` and the
/// agent-to-renderer message schema, into Dart source, so the published
/// package carries them instead of asking every caller to supply them.
///
/// Run from the package directory after editing the specification:
///
/// ```sh
/// dart run tool/generate_protocol_schemas.dart
/// ```
///
/// `test/common_types_test.dart` and `test/agent_to_renderer_schema_test.dart`
/// fail if the checked-in output has drifted from the specification.
library;

import 'dart:io';

/// The files to write, relative to the package directory, each mapped to the
/// specification files it embeds, relative to the repository root, keyed by
/// the Dart constant each is embedded as.
const Map<String, Map<String, String>> outputs = {
  'lib/src/validation/common_types.g.dart': {
    'commonTypesV0_9Json': 'specification/v0_9/json/common_types.json',
    'commonTypesV1_0Json': 'specification/v1_0/json/common_types.json',
  },
  'lib/src/core/agent_to_renderer_schemas.g.dart': {
    'agentToRendererV0_9Json': 'specification/v0_9/json/server_to_client.json',
    'agentToRendererV0_9_1Json':
        'specification/v0_9_1/json/server_to_client.json',
    'agentToRendererV1_0Json': 'specification/v1_0/json/agent_to_renderer.json',
  },
};

void main() {
  for (final MapEntry<String, Map<String, String>> output in outputs.entries) {
    File(output.key).writeAsStringSync(
      render({
        for (final MapEntry<String, String> entry in output.value.entries)
          entry.value: (entry.key, readSource(entry.value)),
      }),
    );
    stdout.writeln(
      'Wrote ${output.key} from ${output.value.values.join(', ')}.',
    );
  }
}

/// Reads [source], searching upwards for the repository root so the tool runs
/// from the package directory or the workspace root.
String readSource(String source) {
  Directory dir = Directory.current;
  while (true) {
    final candidate = File('${dir.path}/$source');
    if (candidate.existsSync()) return candidate.readAsStringSync();
    final Directory parent = dir.parent;
    if (parent.path == dir.path) {
      throw StateError(
        'Could not find $source above ${Directory.current.path}.',
      );
    }
    dir = parent;
  }
}

/// Wraps each document in [documents], keyed by its specification path and
/// paired with its constant name, in a Dart library, verbatim, so the
/// generated file diffs against the specification one line at a time.
///
/// Each document is embedded as a raw multiline string, which reproduces `$`
/// and `\` without escaping. Throws if a document is not expressible that
/// way, so a specification edit cannot silently produce a file that says
/// something other than what it copied.
String render(Map<String, (String, String)> documents) {
  final buffer = StringBuffer('''
// Copyright 2024 Google LLC
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     https://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

// Generated by tool/generate_protocol_schemas.dart. Do not edit by hand.
//
// Verbatim copies of:
${documents.keys.map((s) => '// - $s').join('\n')}
''');
  for (final MapEntry<String, (String, String)> entry in documents.entries) {
    final String source = entry.key;
    final (String name, String json) = entry.value;
    if (json.contains("'''")) {
      throw StateError("$source contains ''', which ends the string literal.");
    }
    if (json.endsWith("'")) {
      throw StateError("$source ends with ', which extends the delimiter.");
    }
    if (!json.startsWith('{')) {
      throw StateError('$source does not start with a JSON object.');
    }
    final RegExpMatch match = RegExp(
      r'specification/v([0-9_]+)/json/([a-z_]+\.json)$',
    ).firstMatch(source)!;
    final String version = match[1]!.replaceAll('_', '.');
    buffer.write('''

/// The `${match[2]}` document for protocol v$version, as published.
const String $name = r\'\'\'
$json\'\'\';
''');
  }
  return buffer.toString();
}
