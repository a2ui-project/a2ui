"""Skill evaluation strategies for A2UI replicating common agent harness patterns.

This module provides two distinct evaluation solvers for assessing model performance
with modular A2UI skills generated by the `SkillGenerator` API:

===================================================================================
1. `skill_preloaded` (Passive Context Injection Pattern)
===================================================================================

- **Harness Representation & Architectural Basis**:
  Represents coding assistants and agent frameworks where domain skills or workspace
  instructions are assembled upfront and injected directly into prompt context
  prior to model invocation:
  * **Google Antigravity & Agent Guidelines**: In Antigravity and repository agents,
    relevant skills in `.agents/skills/*/SKILL.md` or `AGENTS.md` are identified and
    preloaded directly into the context window before execution.
    - Reference: Open AGENTS.md specification: https://github.com/agentsmd/agents.md
  * **LangChain (Prompt Templates / In-Context Prompt Chaining)**: Pre-compiles domain
    instructions and few-shot examples into message history using prompt templates,
    enabling single-turn generation without tool-calling overhead.
    - Reference: https://python.langchain.com/docs/concepts/prompt_templates/
  * **OpenAI (System / Developer Context Injection)**: In standard OpenAI prompting,
    system/developer message instructions provide comprehensive task rules before user input.
    - Reference: https://platform.openai.com/docs/guides/prompt-engineering

- **Context Window Structure**:
  ```
  +-------------------------------------------------------------------------------+
  | [System Turn] ChatMessageSystem                                               |
  | Content: Domain instructions or default system role prompt                    |
  |          ("You are an AI assistant. Help the user by generating UI...")       |
  +-------------------------------------------------------------------------------+
  | [User Turn] ChatMessageUser                                                   |
  | Content: Here are the pre-loaded A2UI UI generation rules and component       |
  |          signatures:                                                          |
  |                                                                               |
  |          ---                                                                  |
  |          name: a2ui                                                           |
  |          description: Agent-to-User Interface specification                   |
  |          ---                                                                  |
  |          # Protocol Rules                                                     |
  |          ...                                                                  |
  |          # Component Catalog Signatures                                       |
  |          ...                                                                  |
  |                                                                               |
  |          User Request: <Original Task Prompt from dataset>                    |
  +-------------------------------------------------------------------------------+
  | [Assistant Turn] ChatMessageAssistant (Model Output)                          |
  | Content: <a2ui>                                                               |
  |          ... generated UI payload ...                                         |
  |          </a2ui>                                                              |
  +-------------------------------------------------------------------------------+
  ```
- **Execution Characteristics**: Single-turn generation with zero tool-calling latency.

===================================================================================
2. `skill_interactive_tool` (Active Dynamic Retrieval Pattern)
===================================================================================

- **Harness Representation & Architectural Basis**:
  Represents tool-augmented runtime agent harnesses where the context window is kept
  minimal, and the model dynamically discovers and queries tools/skills at runtime:
  * **Anthropic Claude Code (`claude`) & Tool Use**: In Claude Code and Claude tool
    workflows, models are not front-loaded with entire rulebooks. The system prompt
    only describes available tools and capabilities. When domain instructions are
    needed, Claude emits a `tool_use` call to fetch the required information on demand.
    - Reference (Anthropic Research): https://www.anthropic.com/research/building-effective-agents
    - Reference (Claude Tool Use): https://docs.anthropic.com/en/docs/build-with-claude/tool-use
  * **Model Context Protocol (MCP)**: Open standard where clients (such as Claude Code)
    dynamically discover and invoke tools from connected servers.
    - Reference: https://modelcontextprotocol.io/introduction
  * **Vercel AI SDK Core (`tools` & Multi-Step Agent Loop)**: Tools are passed to
    `generateText` / `streamText`. The model decides when to invoke tools, and the
    runtime executes them across a multi-turn agent loop (`maxSteps > 1`).
    - Reference: https://sdk.vercel.ai/docs/ai-sdk-core/tools-and-tool-calling
  * **OpenAI Function Calling / Assistants API**: Models receive function definitions
    and autonomously generate function calls (`tool_calls`) across multi-turn exchanges.
    - Reference: https://platform.openai.com/docs/guides/function-calling

- **Context Window Structure**:
  ```
  +-------------------------------------------------------------------------------+
  | [System Turn] ChatMessageSystem                                               |
  | Content: "You are a helpful AI assistant. You have access to specialized       |
  |           skills for UI generation.                                           |
  |                                                                               |
  |           ## Available Skills                                                 |
  |           - a2ui-core: Core A2UI protocol concepts and layout rules...        |
  |           - a2ui-0.9: Basic catalog components and layouts...                 |
  |                                                                               |
  |           When the user requests a user interface, call the `load_skill`      |
  |           tool to retrieve the required syntax before producing UI..."        |
  +-------------------------------------------------------------------------------+
  | [User Turn 1] ChatMessageUser                                                 |
  | Content: <Original Task Prompt from dataset>                                  |
  +-------------------------------------------------------------------------------+
  | [Assistant Turn 2] ChatMessageAssistant                                       |
  | Tool Call: load_skill(skill_name="a2ui-core")                                 |
  +-------------------------------------------------------------------------------+
  | [Tool Turn 3] ChatMessageTool                                                 |
  | Content: <Full markdown of requested a2ui-core skill>                         |
  +-------------------------------------------------------------------------------+
  | (Optional Turns: Assistant calls load_skill("a2ui-0.9"), etc.)                |
  +-------------------------------------------------------------------------------+
  | [Assistant Final Turn] ChatMessageAssistant                                   |
  | Content: <a2ui>                                                               |
  |          ... generated UI payload ...                                         |
  |          </a2ui>                                                              |
  +-------------------------------------------------------------------------------+
  ```
- **Execution Characteristics**: Multi-turn conversational exchange requiring autonomous
  tool dispatch (`load_skill`) before generating the final UI specification.
"""

from typing import Any, Optional
from inspect_ai.solver import (
    Generate,
    Solver,
    solver,
    TaskState,
    use_tools,
)
from inspect_ai.model import (
    ChatMessageAssistant,
    ChatMessageSystem,
    ChatMessageTool,
    ChatMessageUser,
)
from inspect_ai.tool import tool, Tool
from inspect_ai.util import store

from a2ui.schema.catalog import CatalogConfig
from a2ui.skill import SkillGenerator

from .format import _get_strategy, compile_format_payload
from ..shared.utils import GIT_ROOT, measured_generate


@tool
def load_skill() -> Tool:
    """Tool allowing models to fetch A2UI skills dynamically.

    Simulates dynamic, on-demand skill retrieval in tool-augmented agents (e.g. Claude Code, MCP, Vercel AI SDK).
    """

    async def execute(skill_name: str) -> str:
        """Loads the full markdown content of a requested A2UI skill.

        Args:
            skill_name: The name of the skill to load (e.g. 'a2ui-core', 'a2ui-basic', 'a2ui').
        """
        version = store().get("version", "1.0")
        format_name = store().get("format_name", "express")
        catalog_path = store().get("catalog")

        if not catalog_path:
            raise ValueError("Catalog path missing from task store.")

        resolved_catalog_path = str(GIT_ROOT / catalog_path)
        catalog_config = CatalogConfig.from_path("basic_catalog", resolved_catalog_path)

        strategy = _get_strategy(format_name, version, catalog_config)
        generator = SkillGenerator(strategy)
        skill_set = generator.generate_skillset()

        # Normalize skill lookup key
        key = (
            skill_name if skill_name.endswith("/SKILL.md") else f"{skill_name}/SKILL.md"
        )
        skill = skill_set.get(key) or skill_set.get(skill_name)

        if skill:
            return skill.to_markdown()

        # Fallback to monolithic skill if requested
        if skill_name in ["a2ui", "a2ui/SKILL.md"]:
            mono_skill = generator.generate_skill(name="a2ui")
            return mono_skill.to_markdown()

        available = list(skill_set.to_dict().keys())
        return f"Error: Skill '{skill_name}' not found. Available skills: {available}"

    return execute


@solver
def skill_preloaded_prompt(format_name: str, version: str) -> Solver:
    """Injects skill markdown into User Context as a pre-loaded skill (Passive Context Injection Pattern).

    Context layout:
    - System message: Domain prompt / role instructions.
    - User message: Full skill markdown prepended directly to the user's task prompt.
    """

    async def solve(state: TaskState, generate: Generate) -> TaskState:
        catalog_path = state.metadata["catalog"]
        resolved_catalog_path = str(GIT_ROOT / catalog_path)
        catalog_config = CatalogConfig.from_path("basic_catalog", resolved_catalog_path)

        strategy = _get_strategy(format_name, version, catalog_config)
        generator = SkillGenerator(strategy)
        skill = generator.generate_skill(name="a2ui")

        domain_prompt = state.metadata.get("system_prompt", "").strip()
        state.messages.insert(
            0,
            ChatMessageSystem(
                content=domain_prompt
                or "You are an AI assistant. Help the user by generating user interfaces."
            ),
        )

        # Pre-load skill content directly into user message turn context (Antigravity / LangChain / Copilot Proxy)
        if len(state.messages) > 1 and hasattr(state.messages[-1], "content"):
            user_msg = state.messages[-1]
            user_msg.content = (
                "Here are the pre-loaded A2UI UI generation rules and component"
                f" signatures:\n\n{skill.to_markdown()}\n\nUser Request:"
                f" {user_msg.content}"
            )

        return state

    return solve


@solver
def skill_interactive_system_prompt(format_name: str, version: str) -> Solver:
    """Injects system prompt with skill frontmatter only (Active Agent Tool Retrieval Pattern).

    Context layout:
    - System message: Descriptions of available skills + directive to call `load_skill`.
    - User message: Original user prompt (unmodified).
    """

    async def solve(state: TaskState, generate: Generate) -> TaskState:
        catalog_path = state.metadata["catalog"]
        resolved_catalog_path = str(GIT_ROOT / catalog_path)
        catalog_config = CatalogConfig.from_path("basic_catalog", resolved_catalog_path)

        strategy = _get_strategy(format_name, version, catalog_config)
        generator = SkillGenerator(strategy)
        skill_set = generator.generate_skillset()

        frontmatter_lines = []
        for sk_obj in skill_set.values():
            frontmatter_lines.append(f"- **{sk_obj.name}**: {sk_obj.description}")

        skills_summary = "\n".join(frontmatter_lines)
        system_content = (
            "You are a helpful AI assistant. You have access to specialized skills for"
            f" UI generation.\n\n## Available Skills\n{skills_summary}\n\nWhen the user"
            " requests a user interface, call the `load_skill` tool to retrieve the"
            " required syntax and signatures before producing the UI response."
        )

        domain_prompt = state.metadata.get("system_prompt", "").strip()
        if domain_prompt:
            system_content = f"{domain_prompt}\n\n{system_content}"

        state.messages.insert(0, ChatMessageSystem(content=system_content))

        # Push task metadata to store for tool access
        state.store.set("version", version)
        state.store.set("format_name", format_name)
        state.store.set("catalog", catalog_path)

        return state

    return solve


def skill_preloaded_solver(
    format_name: str = "express", version: str = "1.0"
) -> list[Solver]:
    """Returns the solver chain for the 'skill_preloaded' evaluation strategy (Pre-loaded Harness Proxy)."""
    return [
        skill_preloaded_prompt(format_name, version),
        measured_generate(),
        compile_format_payload(format_name, version),
    ]


def skill_interactive_tool_solver(
    format_name: str = "express", version: str = "1.0"
) -> list[Solver]:
    """Returns the solver chain for the 'skill_interactive_tool' evaluation strategy (Active Agent Retrieval Proxy)."""
    return [
        skill_interactive_system_prompt(format_name, version),
        use_tools([load_skill()]),
        measured_generate(),
        compile_format_payload(format_name, version),
    ]
