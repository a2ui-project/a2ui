class _BlockDumper(yaml.SafeDumper):
    """YAML dumper that renders multi-line strings with literal block scalars."""


def _str_representer(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if data.count("\n") >= 2:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_BlockDumper.add_representer(str, _str_representer)


def _lower_messages(messages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    step_case = {
        "name": "e2e_wire_step",
        "protocolVersion": "1.0",
        "steps": [{"messages": copy.deepcopy(messages)}],
    }
    lowered = lower_adapter_suite.lower_case(step_case)
    assert lowered is not None
    return list(lowered["steps"][0]["messages"])


def _lower_outbound(outbound: list[dict[str, Any]]) -> list[dict[str, Any]]:
    step_case = {
        "name": "e2e_outbound_step",
        "protocolVersion": "1.0",
        "steps": [{"expectOutbound": copy.deepcopy(outbound)}],
    }
    lowered = lower_adapter_suite.lower_case(step_case)
    assert lowered is not None
    return list(lowered["steps"][0]["expectOutbound"])


def _split_into_n_chunks(text: str, original_chunks: list[str]) -> list[str]:
    count = len(original_chunks)
    if count <= 1:
        return [text]
    prefix = "".join(original_chunks[:-1])
    if text.startswith(prefix):
        return [*original_chunks[:-1], text[len(prefix) :]]

    total_orig = sum(len(chunk) for chunk in original_chunks)
    if total_orig == 0:
        step = max(1, len(text) // count)
        bounds = [min(len(text), idx * step) for idx in range(count)] + [len(text)]
        return [text[bounds[idx] : bounds[idx + 1]] for idx in range(count)]

    result: list[str] = []
    cursor = 0
    elapsed = 0
    for chunk in original_chunks[:-1]:
        elapsed += len(chunk)
        next_cursor = round(len(text) * elapsed / total_orig)
        result.append(text[cursor:next_cursor])
        cursor = next_cursor
    result.append(text[cursor:])
    return result


def lower_direct_json_chunks(chunks: list[str]) -> list[str]:
    """Rewrites each <a2ui-json> block with lowered messages and preserves chunk count."""
    if not chunks:
        return []
    joined = "".join(chunks)
    if "<a2ui-json>" not in joined:
        return list(chunks)

    def _replace_block(match: re.Match[str]) -> str:
        raw_payload = json.loads(match.group(1))
        msgs = raw_payload if isinstance(raw_payload, list) else [raw_payload]
        lowered_msgs = _lower_messages(msgs)
        formatted = json.dumps(lowered_msgs, indent=2)
        return f"<a2ui-json>\n{formatted}\n</a2ui-json>"

    rewritten = _A2UI_JSON_BLOCK_RE.sub(_replace_block, joined)
    return _split_into_n_chunks(rewritten, chunks)


def _part_to_dict(part: Any) -> dict[str, Any]:
    if isinstance(part, TextPart):
        return {"text": part.text}
    if isinstance(part, A2uiPart):
        return {"a2ui": to_message_dicts(part.a2ui)}
    if isinstance(part, ErrorPart):
        return {"error": {"category": getattr(part.error, "category", "unknown")}}
    raise TypeError(f"Unexpected stream part: {type(part)}")


def _merge_adjacent_text(parts: list[dict[str, Any]]) -> list[dict[str, Any]]:
    merged: list[dict[str, Any]] = []
    for part in parts:
        if merged and "text" in merged[-1] and "text" in part:
            merged[-1] = {"text": merged[-1]["text"] + part["text"]}
        else:
            merged.append(part)
    return merged


def _seed_uncreated_surfaces(
    state: Any,
    expect_wire: list[dict[str, Any]],
    catalog_id: str,
) -> None:
    created_in_turn = {
        msg["createSurface"]["surfaceId"]
        for part in expect_wire
        for msg in part.get("a2ui", [])
        if "createSurface" in msg
    }
    for part in expect_wire:
        for msg in part.get("a2ui", []):
            if "updateComponents" not in msg:
                continue
            sid = msg["updateComponents"]["surfaceId"]
            if sid not in created_in_turn and state.get_surface(sid) is None:
                state.apply([{
                    "version": "v0.9",
                    "createSurface": {
                        "surfaceId": sid,
                        "catalogId": catalog_id,
                    },
                }])


def _verify_express_turn(
    parser: Any,
    state: Any,
    chunks: list[str],
    expect_wire: list[dict[str, Any]],
    catalog_id: str,
    scenario_name: str,
    turn_idx: int,
) -> None:
    _seed_uncreated_surfaces(state, expect_wire, catalog_id)
    stream = parser.open_stream(state=state)
    parts: list[dict[str, Any]] = []
    for chunk in chunks:
        parts.extend(_part_to_dict(p) for p in stream.feed(chunk))
    parts.extend(_part_to_dict(p) for p in stream.close())
    actual = _merge_adjacent_text(parts)
    if actual != expect_wire:
        raise RuntimeError(
            f"Express v0.9 compilation mismatch in {scenario_name} turn {turn_idx}:\n"
            f"actual={actual}\nexpected={expect_wire}"
        )


def _lower_turn(turn: dict[str, Any]) -> dict[str, Any]:
    lowered_turn = copy.deepcopy(turn)
    model_chunks = lowered_turn.get("modelChunks", {})
    if "direct_json" in model_chunks:
        model_chunks["direct_json"] = lower_direct_json_chunks(
            model_chunks["direct_json"]
        )
    if "express" in model_chunks:
        model_chunks["express"] = list(model_chunks["express"])

    if "expectWire" in lowered_turn:
        new_wire: list[dict[str, Any]] = []
        for wire_part in lowered_turn["expectWire"]:
            if "a2ui" in wire_part:
                new_wire.append({"a2ui": _lower_messages(wire_part["a2ui"])})
            else:
                new_wire.append(copy.deepcopy(wire_part))
        lowered_turn["expectWire"] = new_wire

    if "expectOutbound" in lowered_turn:
        lowered_turn["expectOutbound"] = _lower_outbound(lowered_turn["expectOutbound"])
    return lowered_turn


def lower_scenario(
    case: dict[str, Any],
    seed_rel_path: str,
    v09_catalog: Catalog,
) -> dict[str, Any]:
    """Lowers a single v1.0 E2E scenario dict to v0.9.1 and verifies Express."""
    lowered = copy.deepcopy(case)
    base_name = str(case["name"])
    lowered["name"] = (
        base_name if base_name.endswith("_v0_9_1") else f"{base_name}_v0_9_1"
    )
    lowered["protocolVersion"] = "v0.9"
    lowered["catalogPaths"] = [V091_CATALOG_REL]
    lowered["source"] = {
        "kind": "generated",
        "from": seed_rel_path,
    }
    lowered["turns"] = [_lower_turn(turn) for turn in case.get("turns", [])]

    if "express" in lowered.get("formats", []):
        express_parser = ExpressFormat(
            catalogs=[v09_catalog],
            surface_id="default_surface",
            version="v0.9",
        ).create_parser()
        state = express_parser._empty_state()
        for turn_idx, turn in enumerate(lowered["turns"]):
            _verify_express_turn(
                express_parser,
                state,
                turn["modelChunks"]["express"],
                turn["expectWire"],
                v09_catalog.catalog_id,
                lowered["name"],
                turn_idx,
            )
    return lowered


def render_lowered_file(seed_path: Path, v09_catalog: Catalog) -> str:
    """Renders the full YAML text for a lowered v0.9.1 scenario file."""
    rel_from_repo = seed_path.relative_to(REPO_ROOT).as_posix()
    raw_cases = yaml.safe_load(seed_path.read_text(encoding="utf-8")) or []
    lowered_cases = [
        lower_scenario(case, rel_from_repo, v09_catalog) for case in raw_cases
    ]
    body = yaml.dump(
        lowered_cases,
        Dumper=_BlockDumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=120,
    )
    return HEADER_COMMENT + body


def main(argv: Sequence[str] | None = None) -> int:
    """CLI entry point for lowering v1.0 E2E scenarios to v0.9.1."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify generated files on disk match lowered output without writing.",
    )
    args = parser.parse_args(argv)

    catalog_data = json.loads(V091_CATALOG_PATH.read_text(encoding="utf-8"))
    v09_catalog = Catalog.from_json(catalog_data)
    seed_files = sorted(E2E_DIR.glob("*.yaml"))
    if not seed_files:
        sys.stderr.write(f"No seed scenarios found in {E2E_DIR}\n")
        return 1

    stale: list[Path] = []
    for seed_path in seed_files:
        expected_content = render_lowered_file(seed_path, v09_catalog)
        out_path = OUTPUT_DIR / seed_path.name
        if args.check:
            if not out_path.exists():
                sys.stderr.write(f"Missing generated scenario: {out_path}\n")
                stale.append(out_path)
            else:
                disk_text = out_path.read_text(encoding="utf-8")
                if not disk_text.startswith(
                    "# DO NOT EDIT - generated by"
                    " conformance/scripts/lower_e2e_scenarios.py"
                ) or yaml.safe_load(disk_text) != yaml.safe_load(expected_content):
                    sys.stderr.write(f"Out-of-date generated scenario: {out_path}\n")
                    stale.append(out_path)
        else:
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(expected_content, encoding="utf-8")
            print(f"Generated {out_path.relative_to(REPO_ROOT)}")

    if args.check:
        if stale:
            return 1
        print(f"Verified {len(seed_files)} lowered v0.9.1 E2E scenarios.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
