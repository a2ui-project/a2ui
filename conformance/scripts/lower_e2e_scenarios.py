"""Lowers conformance/e2e/*.yaml scenarios from v1.0 to v0.9.1."""

from __future__ import annotations

import argparse
from collections.abc import Sequence
import copy
import json
from pathlib import Path
import re
import sys
from typing import Any

from a2ui.core import Catalog
from a2ui.inference_formats import to_message_dicts
from a2ui.inference_formats.express import ExpressFormat
from a2ui.parser import A2uiPart
from a2ui.parser import ErrorPart
from a2ui.parser import TextPart
import yaml

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import lower_adapter_suite  # type: ignore[import-not-found]  # pylint: disable=wrong-import-position

REPO_ROOT = SCRIPT_DIR.parent.parent
E2E_DIR = REPO_ROOT / "conformance" / "e2e"
OUTPUT_DIR = E2E_DIR / "v0_9_1"
V091_CATALOG_REL = "specification/v0_9_1/catalogs/basic/catalog.json"
V091_CATALOG_PATH = REPO_ROOT / V091_CATALOG_REL

_A2UI_JSON_BLOCK_RE = re.compile(
    r"<a2ui-json>\s*(.*?)\s*</a2ui-json>",
    re.DOTALL,
)

