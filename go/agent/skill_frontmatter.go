// The SKILL.md frontmatter is written the way PyYAML's `yaml.dump(..., sort_keys=False)`
// writes it, so that skills generated by every SDK are byte-identical: block style,
// scalars folded at a preferred width of 80 columns, ASCII-only output, and the plain,
// single-quoted or double-quoted style PyYAML's emitter picks for each string.

const (
	frontmatterBestWidth  = 80
	frontmatterBestIndent = 2
)

// frontmatterImplicitREs match plain scalars that a YAML 1.1 resolver reads as something
// other than a string (PyYAML's implicit resolvers), so such strings must be quoted.
var frontmatterImplicitREs = []*regexp.Regexp{
	regexp.MustCompile(`^(?:yes|Yes|YES|no|No|NO|true|True|TRUE|false|False|FALSE|on|On|ON|off|Off|OFF)$`),
	regexp.MustCompile(`^(?:[-+]?(?:[0-9][0-9_]*)\.[0-9_]*(?:[eE][-+][0-9]+)?|\.[0-9][0-9_]*(?:[eE][-+][0-9]+)?|[-+]?[0-9][0-9_]*(?::[0-5]?[0-9])+\.[0-9_]*|[-+]?\.(?:inf|Inf|INF)|\.(?:nan|NaN|NAN))$`),
	regexp.MustCompile(`^(?:[-+]?0b[0-1_]+|[-+]?0[0-7_]+|[-+]?(?:0|[1-9][0-9_]*)|[-+]?0x[0-9a-fA-F_]+|[-+]?[1-9][0-9_]*(?::[0-5]?[0-9])+)$`),
	regexp.MustCompile(`^(?:<<)$`),
	regexp.MustCompile(`^(?:~|null|Null|NULL|)$`),
	regexp.MustCompile(`^(?:[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]|[0-9][0-9][0-9][0-9]-[0-9][0-9]?-[0-9][0-9]?(?:[Tt]|[ \t]+)[0-9][0-9]?:[0-9][0-9]:[0-9][0-9](?:\.[0-9]*)?(?:[ \t]*(?:Z|[-+][0-9][0-9]?(?::[0-9][0-9])?))?)$`),
	regexp.MustCompile(`^(?:=)$`),
}

var frontmatterEscapes = map[rune]string{
	0x00:   "0",
	0x07:   "a",
	0x08:   "b",
	0x09:   "t",
	0x0A:   "n",
	0x0B:   "v",
	0x0C:   "f",
	0x0D:   "r",
	0x1B:   "e",
	'"':    "\"",
	'\\':   "\\",
	0x85:   "N",
	0xA0:   "_",
	0x2028: "L",
	0x2029: "P",
}

type frontmatterEntry struct {
	key   string
	value any
}

// frontmatterWriter tracks the output column, as PyYAML's emitter does, to fold long scalars.
type frontmatterWriter struct {
	sb     strings.Builder
	column int
}

// marshalFrontmatter renders entries as a top-level YAML block mapping.
func marshalFrontmatter(entries []frontmatterEntry) string {
	w := &frontmatterWriter{}
	w.writeMapping(entries, 0)
	return w.sb.String()
}

func (w *frontmatterWriter) write(s string) {
	w.sb.WriteString(s)
	if idx := strings.LastIndexByte(s, '\n'); idx >= 0 {
		w.column = len([]rune(s[idx+1:]))
		return
	}
	w.column += len([]rune(s))
}

func (w *frontmatterWriter) writeIndent(indent int) {
	if w.column != 0 {
		w.write("\n")
	}
	if w.column < indent {
		w.write(strings.Repeat(" ", indent-w.column))
	}
}

func (w *frontmatterWriter) writeMapping(entries []frontmatterEntry, indent int) {
	for _, entry := range entries {
		w.writeIndent(indent)
		w.writeKey(entry.key)
		w.write(":")
		w.writeValue(entry.value, indent, true)
	}
}

func (w *frontmatterWriter) writeKey(key string) {
	style := chooseFrontmatterStyle(key, true)
	switch style {
	case '\'':
		w.write("'" + strings.ReplaceAll(key, "'", "''") + "'")
	case '"':
		w.write(`"` + escapeFrontmatterDoubleQuoted(key) + `"`)
	default:
		w.write(key)
	}
}

// writeValue writes the value of a mapping entry or sequence item. indent is the
// indentation of the enclosing collection; scalars fold at indent+2.
func (w *frontmatterWriter) writeValue(value any, indent int, inMapping bool) {
	norm := value
	if _, isBytes := value.([]byte); !isBytes {
		norm = core.CloneJSONValue(value)
	}
	switch v := norm.(type) {
	case map[string]any:
		if len(v) == 0 {
			w.write(" {}")
			return
		}
		keys := make([]string, 0, len(v))
		for k := range v {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		entries := make([]frontmatterEntry, len(keys))
		for i, k := range keys {
			entries[i] = frontmatterEntry{key: k, value: v[k]}
		}
		w.writeMapping(entries, indent+frontmatterBestIndent)
	case []any:
		w.writeSequence(v, indent, inMapping)
	default:
		if norm != nil {
			rv := reflect.ValueOf(norm)
			if rv.Kind() == reflect.Map {
				if rv.IsNil() {
					w.writeScalar(nil, indent+frontmatterBestIndent)
					return
				}
				if rv.Len() == 0 {
					w.write(" {}")
					return
				}
				rawKeys := rv.MapKeys()
				type kv struct {
					key string
					val any
				}
				kvs := make([]kv, len(rawKeys))
				for i, rk := range rawKeys {
					kvs[i] = kv{key: fmt.Sprint(rk.Interface()), val: rv.MapIndex(rk).Interface()}
				}
				sort.Slice(kvs, func(i, j int) bool { return kvs[i].key < kvs[j].key })
				entries := make([]frontmatterEntry, len(kvs))
				for i, item := range kvs {
					entries[i] = frontmatterEntry{key: item.key, value: item.val}
				}
				w.writeMapping(entries, indent+frontmatterBestIndent)
				return
			}
		}
		w.writeScalar(norm, indent+frontmatterBestIndent)
	}
}

func (w *frontmatterWriter) writeSequence(items []any, indent int, inMapping bool) {
	if len(items) == 0 {
		w.write(" []")
		return
	}
	// PyYAML writes a sequence that is a mapping value without indenting it.
	seqIndent := indent
	if !inMapping {
		seqIndent = indent + frontmatterBestIndent
	}
	for _, item := range items {
		normItem := item
		if _, isBytes := item.([]byte); !isBytes {
			normItem = core.CloneJSONValue(item)
		}
		w.writeIndent(seqIndent)
		w.write("-")
		if m, ok := normItem.(map[string]any); ok && len(m) > 0 {
			keys := make([]string, 0, len(m))
			for k := range m {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for i, k := range keys {
				if i == 0 {
					w.write(" ")
				} else {
					w.writeIndent(seqIndent + frontmatterBestIndent)
				}
				w.writeKey(k)
				w.write(":")
				w.writeValue(m[k], seqIndent+frontmatterBestIndent, true)
			}
			continue
		}
		w.writeValue(normItem, seqIndent, false)
	}
}

func (w *frontmatterWriter) writeScalar(value any, indent int) {
	switch v := value.(type) {
	case nil:
		w.write(" null")
	case bool:
		w.write(" " + strconv.FormatBool(v))
	case int:
		w.write(" " + strconv.Itoa(v))
	case int8:
		w.write(" " + strconv.FormatInt(int64(v), 10))
	case int16:
		w.write(" " + strconv.FormatInt(int64(v), 10))
	case int32:
		w.write(" " + strconv.FormatInt(int64(v), 10))
	case int64:
		w.write(" " + strconv.FormatInt(v, 10))
	case uint:
		w.write(" " + strconv.FormatUint(uint64(v), 10))
	case uint8:
		w.write(" " + strconv.FormatUint(uint64(v), 10))
	case uint16:
		w.write(" " + strconv.FormatUint(uint64(v), 10))
	case uint32:
		w.write(" " + strconv.FormatUint(uint64(v), 10))
	case uint64:
		w.write(" " + strconv.FormatUint(v, 10))
	case float32:
		w.write(" " + formatFrontmatterFloat(float64(v)))
	case float64:
		w.write(" " + formatFrontmatterFloat(v))
	case json.Number:
		if i, err := v.Int64(); err == nil {
			w.write(" " + strconv.FormatInt(i, 10))
		} else if f, err := v.Float64(); err == nil {
			w.write(" " + formatFrontmatterFloat(f))
		} else {
			w.writeScalar(v.String(), indent)
		}
	case string:
		switch chooseFrontmatterStyle(v, false) {
		case 0:
			w.writePlain(v, indent)
		case '\'':
			w.writeSingleQuoted(v, indent)
		default:
			w.writeDoubleQuoted(v, indent)
		}
	default:
		w.writeDoubleQuoted(fmt.Sprint(v), indent)
	}
}

// formatFrontmatterFloat follows PyYAML's represent_float, which writes Python's repr.
func formatFrontmatterFloat(f float64) string {
	switch {
	case math.IsNaN(f):
		return ".nan"
	case math.IsInf(f, 1):
		return ".inf"
	case math.IsInf(f, -1):
		return "-.inf"
	}
	exp := 0
	if f != 0 {
		exp = int(math.Floor(math.Log10(math.Abs(f))))
	}
	var out string
	if exp < -4 || exp >= 16 {
		out = strconv.FormatFloat(f, 'e', -1, 64)
		if !strings.Contains(out, ".") {
			out = strings.Replace(out, "e", ".0e", 1)
		}
	} else {
		out = strconv.FormatFloat(f, 'f', -1, 64)
		if !strings.Contains(out, ".") {
			out += ".0"
		}
	}
	return out
}

func isFrontmatterBreak(ch rune) bool {
	return ch == '\n' || ch == 0x85 || ch == 0x2028 || ch == 0x2029
}

func isFrontmatterSpaceOrBreak(ch rune) bool {
	return ch == 0 || ch == ' ' || ch == '\t' || ch == '\r' || isFrontmatterBreak(ch)
}

// chooseFrontmatterStyle mirrors PyYAML's analyze_scalar and choose_scalar_style with
// allow_unicode disabled. It returns 0 for plain, '\'' for single-quoted, or '"'.
func chooseFrontmatterStyle(s string, simpleKey bool) rune {
	runes := []rune(s)
	if len(runes) == 0 {
		return '\''
	}
	// Flow indicators only matter for flow-style collections, which the frontmatter never uses.
	var blockIndicators, lineBreaks, specialCharacters bool
	var leadingSpace, leadingBreak, trailingSpace, trailingBreak, breakSpace, spaceBreak bool
	if strings.HasPrefix(s, "---") || strings.HasPrefix(s, "...") {
		blockIndicators = true
	}
	precededByWhitespace := true
	followedByWhitespace := len(runes) == 1 || isFrontmatterSpaceOrBreak(runes[1])
	previousSpace := false
	previousBreak := false
	for index, ch := range runes {
		if index == 0 {
			if strings.ContainsRune("#,[]{}&*!|>'\"%@`", ch) {
				blockIndicators = true
			}
			if (ch == '?' || ch == ':' || ch == '-') && followedByWhitespace {
				blockIndicators = true
			}
		} else {
			if ch == ':' && followedByWhitespace {
				blockIndicators = true
			}
			if ch == '#' && precededByWhitespace {
				blockIndicators = true
			}
		}
		if isFrontmatterBreak(ch) {
			lineBreaks = true
		}
		if !(ch == '\n' || (ch >= 0x20 && ch <= 0x7E)) {
			// Without allow_unicode, every other character is written escaped.
			specialCharacters = true
		}
		switch {
		case ch == ' ':
			if index == 0 {
				leadingSpace = true
			}
			if index == len(runes)-1 {
				trailingSpace = true
			}
			if previousBreak {
				breakSpace = true
			}
			previousSpace = true
			previousBreak = false
		case isFrontmatterBreak(ch):
			if index == 0 {
				leadingBreak = true
			}
			if index == len(runes)-1 {
				trailingBreak = true
			}
			if previousSpace {
				spaceBreak = true
			}
			previousSpace = false
			previousBreak = true
		default:
			previousSpace = false
			previousBreak = false
		}
		precededByWhitespace = isFrontmatterSpaceOrBreak(ch)
		followedByWhitespace = index+2 >= len(runes) || isFrontmatterSpaceOrBreak(runes[index+2])
	}

	allowBlockPlain := true
	allowSingleQuoted := true
	if leadingSpace || leadingBreak || trailingSpace || trailingBreak {
		allowBlockPlain = false
	}
	if breakSpace {
		allowBlockPlain = false
		allowSingleQuoted = false
	}
	if spaceBreak || specialCharacters {
		allowBlockPlain = false
		allowSingleQuoted = false
	}
	if lineBreaks {
		allowBlockPlain = false
	}
	if blockIndicators {
		allowBlockPlain = false
	}

	implicitString := true
	for _, re := range frontmatterImplicitREs {
		if re.MatchString(s) {
			implicitString = false
			break
		}
	}
	if implicitString && allowBlockPlain && !(simpleKey && lineBreaks) {
		return 0
	}
	if allowSingleQuoted && !(simpleKey && lineBreaks) {
		return '\''
	}
	return '"'
}

func (w *frontmatterWriter) writePlain(text string, indent int) {
	w.write(" ")
	runes := []rune(text)
	spaces := false
	start := 0
	for end := 0; end <= len(runes); end++ {
		ch := rune(-1)
		if end < len(runes) {
			ch = runes[end]
		}
		if spaces {
			if ch != ' ' {
				if start+1 == end && w.column > frontmatterBestWidth {
					w.writeIndent(indent)
				} else {
					w.write(string(runes[start:end]))
				}
				start = end
			}
		} else if ch == -1 || ch == ' ' {
			w.write(string(runes[start:end]))
			start = end
		}
		if ch != -1 {
			spaces = ch == ' '
		}
	}
}

func (w *frontmatterWriter) writeSingleQuoted(text string, indent int) {
	w.write(" '")
	runes := []rune(text)
	spaces := false
	breaks := false
	start := 0
	for end := 0; end <= len(runes); end++ {
		ch := rune(-1)
		if end < len(runes) {
			ch = runes[end]
		}
		switch {
		case spaces:
			if ch != ' ' {
				if start+1 == end && w.column > frontmatterBestWidth && start != 0 && end != len(runes) {
					w.writeIndent(indent)
				} else {
					w.write(string(runes[start:end]))
				}
				start = end
			}
		case breaks:
			if ch == -1 || !isFrontmatterBreak(ch) {
				if runes[start] == '\n' {
					w.write("\n")
				}
				for _, br := range runes[start:end] {
					if br == '\n' {
						w.write("\n")
					} else {
						w.write(string(br) + "\n")
					}
				}
				w.writeIndent(indent)
				start = end
			}
		default:
			if (ch == -1 || ch == ' ' || isFrontmatterBreak(ch) || ch == '\'') && start < end {
				w.write(string(runes[start:end]))
				start = end
			}
		}
		if ch == '\'' {
			w.write("''")
			start = end + 1
		}
		if ch != -1 {
			spaces = ch == ' '
			breaks = isFrontmatterBreak(ch)
		}
	}
	w.write("'")
}

func escapeFrontmatterRune(ch rune) string {
	if rep, ok := frontmatterEscapes[ch]; ok {
		return `\` + rep
	}
	switch {
	case ch <= 0xFF:
		return fmt.Sprintf(`\x%02X`, ch)
	case ch <= 0xFFFF:
		return fmt.Sprintf(`\u%04X`, ch)
	default:
		return fmt.Sprintf(`\U%08X`, ch)
	}
}

func needsFrontmatterEscape(ch rune) bool {
	return ch == '"' || ch == '\\' || ch == 0x85 || ch == 0x2028 || ch == 0x2029 || ch == 0xFEFF ||
		ch < 0x20 || ch > 0x7E
}

func escapeFrontmatterDoubleQuoted(text string) string {
	var sb strings.Builder
	for _, ch := range text {
		if needsFrontmatterEscape(ch) {
			sb.WriteString(escapeFrontmatterRune(ch))
		} else {
			sb.WriteRune(ch)
		}
	}
	return sb.String()
}

func (w *frontmatterWriter) writeDoubleQuoted(text string, indent int) {
	w.write(` "`)
	runes := []rune(text)
	start := 0
	for end := 0; end <= len(runes); end++ {
		ch := rune(-1)
		if end < len(runes) {
			ch = runes[end]
		}
		if ch == -1 || needsFrontmatterEscape(ch) {
			if start < end {
				w.write(string(runes[start:end]))
				start = end
			}
			if ch != -1 {
				w.write(escapeFrontmatterRune(ch))
				start = end + 1
			}
		}
		if end > 0 && end < len(runes)-1 && (ch == ' ' || start >= end) &&
			w.column+(end-start) > frontmatterBestWidth {
			data := string(runes[start:end]) + `\`
			if start < end {
				start = end
			}
			w.write(data)
			w.writeIndent(indent)
			if runes[start] == ' ' {
				w.write(`\`)
			}
		}
	}
	w.write(`"`)
}
