/** Swaps any outdoor stops in `stops` to their indoor `Rain backup` option when available. */
export function applyRainBackups(scenario: ScenarioId, stops: readonly StopItem[]): StopItem[] {
  const swaps = SCENARIO_FIXTURES[scenario].stopSwaps ?? {};
  return stops.map(stop => {
    if (stop.indoor || stop.locked) return {...stop};
    const candidates = swaps[stop.id] ?? [];
    const rainPick =
      candidates.find(opt => opt.badge.toLowerCase().includes('rain')) ??
      candidates.find(opt => opt.indoor);
    if (!rainPick) return {...stop, indoor: true};
    return {
      ...stop,
      title: rainPick.title,
      area: rainPick.area || stop.area,
      category: rainPick.category,
      cost: rainPick.cost,
      durationMin: rainPick.durationMin ?? stop.durationMin,
      openMin: rainPick.openMin ?? stop.openMin,
      closeMin: rainPick.closeMin ?? stop.closeMin,
      indoor: true,
      x: rainPick.x,
      y: rainPick.y,
      optionId: rainPick.id,
    };
  });
}
