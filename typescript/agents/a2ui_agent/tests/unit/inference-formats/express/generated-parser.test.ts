import {readFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

import {ATNDeserializer, CharStream, CommonTokenStream} from 'antlr4ng';
import {describe, expect, it} from 'vitest';

import {ExpressLexer} from '../../../../src/inference-formats/express/generated/ExpressLexer.js';
import {ExpressParser} from '../../../../src/inference-formats/express/generated/ExpressParser.js';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../../../..');
const pythonGeneratedDir = resolve(
  repoRoot,
  'python/a2ui_agent/src/a2ui/inference_formats/express/generated',
);

/**
 * Extracts the serialized ATN from a Python module generated by ANTLR. The
 * values sit between `def serializedATN():` and the class declaration that
 * follows it.
 */
function pythonSerializedAtn(fileName: string): number[] {
  const source = readFileSync(resolve(pythonGeneratedDir, fileName), 'utf8');
  const match = /def serializedATN\(\):([\s\S]*?)\nclass /.exec(source);
  if (!match) {
    throw new Error(`No serializedATN() found in ${fileName}`);
  }
  return (match[1].match(/-?\d+/g) ?? []).map(Number);
}

describe('generated Express parser', () => {
  // The serialized ATN decides every lexing and parsing decision. Identical
  // ATNs mean the TypeScript and Python SDKs accept exactly the same inputs and
  // build the same trees, regardless of which tool generated each one. A
  // failure here means one SDK was regenerated from a different grammar.
  it('has the same parser ATN as the Python SDK', () => {
    const expected = pythonSerializedAtn('express_parser.py');
    expect(expected.length).toBeGreaterThan(0);
    expect(ExpressParser._serializedATN).toEqual(expected);
  });

  it('has the same lexer ATN structure as the Python SDK', () => {
    const expected = pythonSerializedAtn('express_lexer.py');
    expect(expected.length).toBeGreaterThan(0);

    // Python's lexer is generated with Java ANTLR 4.13.2 (ICU4J Unicode 15.0)
    // and TypeScript's with antlr-ng 1.0.10 (Unicode 16.0), so the expanded
    // \p{XID_Start} and \p{XID_Continue} interval tables differ on newly
    // assigned Unicode 16.0 code points while the ATN state graph, rules,
    // modes, and transition topology remain identical.
    const tsAtn = new ATNDeserializer().deserialize(ExpressLexer._serializedATN);
    const pyAtn = new ATNDeserializer().deserialize(expected);

    expect(tsAtn.states.length).toBe(pyAtn.states.length);
    expect(tsAtn.ruleToStartState.map(s => s?.stateNumber)).toEqual(
      pyAtn.ruleToStartState.map(s => s?.stateNumber),
    );
    expect(tsAtn.ruleToTokenType).toEqual(pyAtn.ruleToTokenType);
    expect(tsAtn.modeToStartState.map(s => s?.stateNumber)).toEqual(
      pyAtn.modeToStartState.map(s => s?.stateNumber),
    );
    for (let i = 0; i < tsAtn.states.length; i++) {
      const tsTransitions = tsAtn.states[i]!.transitions.map(t => [
        t.serializationType,
        t.target.stateNumber,
      ]);
      const pyTransitions = pyAtn.states[i]!.transitions.map(t => [
        t.serializationType,
        t.target.stateNumber,
      ]);
      expect(tsTransitions).toEqual(pyTransitions);
    }
  });

  it('parses a program through the antlr4ng runtime', () => {
    const lexer = new ExpressLexer(
      CharStream.fromString('root = Column([title])\ntitle = Text("Hello")\n'),
    );
    const parser = new ExpressParser(new CommonTokenStream(lexer));
    parser.removeErrorListeners();

    const program = parser.program();

    expect(parser.numberOfSyntaxErrors).toBe(0);
    expect(program.statement()).toHaveLength(2);
  });

  it('reports a syntax error for malformed input', () => {
    const lexer = new ExpressLexer(CharStream.fromString('root = Column(['));
    const parser = new ExpressParser(new CommonTokenStream(lexer));
    parser.removeErrorListeners();

    parser.program();

    expect(parser.numberOfSyntaxErrors).toBeGreaterThan(0);
  });
});
