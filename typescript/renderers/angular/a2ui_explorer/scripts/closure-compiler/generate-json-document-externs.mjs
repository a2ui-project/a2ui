/**
 * generate-json-document-externs.mjs
 *
 * Writes `externs/json_documents.externs.js`: every object key of the JSON documents that the
 * explorer bundle contains, which are the JSON Schema documents `@a2ui/web_core` imports (the
 * specification's message, common types and basic catalog schemas) and Ajv's meta-schemas.
 *
 * Why: esbuild inlines an imported JSON document as an object literal with unquoted keys
 * (`{$ref: "#/$defs/DynamicString", properties: {surfaceId: ...}}`), and Closure Compiler in
 * ADVANCED mode renames unquoted keys. The validator reads those keys as strings: Ajv matches
 * keywords (`$id`, `properties`, `oneOf`, ...) by name, a `$ref` JSON Pointer
 * (`#/$defs/DynamicString`) names its target, and a `properties` key is the property name of the
 * validated message. Declaring each key in an extern keeps its name.
 *
 * Run `node scripts/closure-compiler/generate-json-document-externs.mjs` after the
 * specification's JSON documents change; `--check` fails when the checked-in file is stale.
 */

import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';
import {createRequire} from 'module';

const require = createRequire(import.meta.url);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(__dirname, 'externs/json_documents.externs.js');
const webCoreSrc = path.resolve(__dirname, '../../../../../core/web_core/src');

/** Lists the files under `dir` that `keep` accepts. */
function walk(dir, keep) {
  const found = [];
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) found.push(...walk(full, keep));
    else if (keep(full)) found.push(full);
  }
  return found;
}

/** The JSON documents web_core's library sources import. */
function webCoreDocuments() {
  const documents = new Set();
  const sources = walk(webCoreSrc, f => f.endsWith('.ts') && !f.endsWith('.test.ts'));
  for (const source of sources) {
    const text = fs.readFileSync(source, 'utf8');
    for (const match of text.matchAll(/from\s+'([^']+\.json)'\s+with\s+\{type:\s*'json'\}/g)) {
      documents.add(path.resolve(path.dirname(source), match[1]));
    }
  }
  return [...documents];
}

/** Ajv's bundled meta-schemas. */
function ajvDocuments() {
  const refs = path.join(path.dirname(require.resolve('ajv/package.json')), 'dist/refs');
  return walk(refs, f => f.endsWith('.json'));
}

/** Adds every object key of `value` to `keys`. */
function collectKeys(value, keys) {
  if (Array.isArray(value)) {
    for (const item of value) collectKeys(item, keys);
  } else if (value !== null && typeof value === 'object') {
    for (const [key, item] of Object.entries(value)) {
      keys.add(key);
      collectKeys(item, keys);
    }
  }
}

const keys = new Set();
for (const document of [...webCoreDocuments(), ...ajvDocuments()].sort()) {
  collectKeys(JSON.parse(fs.readFileSync(document, 'utf8')), keys);
}
// esbuild quotes keys that are not identifiers (`@path`, `~standard`), and Closure Compiler keeps
// quoted keys, so only identifier keys need an extern.
const identifiers = [...keys].filter(key => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key)).sort();

const header = fs
  .readFileSync(fileURLToPath(import.meta.url), 'utf8')
  .split('\n')
  .slice(0, 15)
  .join('\n')
  .replace(/Copyright \d+/, 'Copyright 2026');

const output = `${header}

/**
 * @externs
 * @fileoverview Generated by \`scripts/closure-compiler/generate-json-document-externs.mjs\`; do
 * not edit. Every identifier key of the JSON Schema documents \`@a2ui/web_core\` imports and of
 * Ajv's meta-schemas, which esbuild inlines with unquoted keys and the validator reads by name.
 */

/**
 * Externs for the keys of the JSON documents bundled into the explorer.
 * @record
 * @struct
 */
function JsonDocumentExterns() {}
${identifiers.map(key => `/** @type {?} */ JsonDocumentExterns.prototype.${key};`).join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error(
      `${path.relative(process.cwd(), outputPath)} is stale. Run node ${path.relative(
        process.cwd(),
        fileURLToPath(import.meta.url),
      )}.`,
    );
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, output, 'utf8');
  console.log(`Wrote ${identifiers.length} keys to ${path.relative(process.cwd(), outputPath)}.`);
}
